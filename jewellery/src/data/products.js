// Helper selectors
export const getProductById = (id) =>
  products.find(
    (p) =>
      String(p.id).toLowerCase() === String(id).toLowerCase() ||
      (p.productId && p.productId.toLowerCase() === String(id).toLowerCase()) ||
      p.id === parseInt(id) ||
      (String(id) === "1" && p.productId === "DK-RNG-001") ||
      (String(id) === "2" && p.productId === "DK-RNG-002") ||
      (String(id) === "3" && p.productId === "DK-RNG-003") ||
      (String(id) === "6" && p.productId === "DK-ERG-001") ||
      (String(id) === "7" && p.productId === "DK-ERG-002") ||
      (String(id) === "24" && p.productId === "DK-PND-001")
  );

export const getProductsByMetal = (metal) =>
  products.filter((p) => p.metal === metal);

export const getProductsByCategory = (category) =>
  products.filter((p) => p.category?.toLowerCase() === category?.toLowerCase());

export const getBestSellers = () =>
  products.filter((p) => p.isBestSeller);

export const getNewArrivals = () =>
  products.filter((p) => p.isNew);

export const getTrendingProducts = () =>
  products.filter((p) => p.isTrending);

export const getFeaturedProducts = () =>
  products.filter((p) => p.isFeatured);

export const getBridalProducts = () =>
  products.filter((p) => p.isBridal);

export const getDiamondProducts = () =>
  products.filter((p) => p.isDiamond);
